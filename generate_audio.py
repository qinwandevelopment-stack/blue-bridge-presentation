NARRATION = {}
for index, (intro, scenario) in enumerate(FOCUS_NARRATIONS, start=1):
    NARRATION[f"slide-{index:02}.mp3"] = f"{intro} {scenario}"
    NARRATION[f"focus-{index:02}-intro.mp3"] = intro
    NARRATION[f"focus-{index:02}-scenario.mp3"] = scenario


async def main():
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    for filename, text in NARRATION.items():
        output_path = OUTPUT_DIR / filename
        if output_path.exists():
            print(f"skipped {output_path}")
            continue
        communicate = edge_tts.Communicate(text, VOICE, rate="-8%", pitch="-4Hz")
        await communicate.save(str(output_path))
        print(f"generated {output_path}")


if __name__ == "__main__":
    asyncio.run(main())
